# Build two indexes for fast lookup
_series_to_eans = {}
_desc_to_ean = {}

for series, description, ean in PRODUCT_DATA:
    series_key = series.strip().upper()
    _series_to_eans.setdefault(series_key, []).append(ean)
    # Map description fragments → EAN
    desc_key = description.strip().upper()
    _desc_to_ean[desc_key] = ean

def resolve_products(query: str) -> list[str]:
    """
    Given a user query (French or English), return matching EAN codes.
    Checks series name first (can return many), then description (returns one).
    Returns empty list if nothing matched.
    """
    q = query.strip().upper()
    matched = []

    # 1. Exact series match
    if q in _series_to_eans:
        return _series_to_eans[q]

    # 2. Series substring match (e.g. user typed "HYDRA" → matches "HYDRA VEGETAL")
    for series_key, eans in _series_to_eans.items():
        if q in series_key or series_key in q:
            matched.extend(eans)

    if matched:
        return list(dict.fromkeys(matched))  # deduplicate, preserve order

    # 3. Description exact match
    if q in _desc_to_ean:
        return [_desc_to_ean[q]]

    # 4. Description substring match
    for desc_key, ean in _desc_to_ean.items():
        if q in desc_key:
            matched.append(ean)

    return list(dict.fromkeys(matched))


